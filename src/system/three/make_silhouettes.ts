// Makes src/system/three/silhouettes.gen.ts: the silhouette table of each model (see silhouette.ts).
// Usage (the untell lab): bun src/system/three/make_silhouettes.ts            every model in the media tables
//                         bun src/system/three/make_silhouettes.ts <name>=<file.glb> ...
// A project's `untell media add` calls silhouetteOfGlb for a new model and keeps the result with the model's bounds.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { gltfBounds, gltfJson } from "./model";
import { PITCHES, YAWS, silhouetteOfGlb, viewAt, type Silhouette } from "./silhouette";
import { MODELS } from "../media.gen";
import { SILHOUETTES } from "./silhouettes.gen";
const ROOT = resolve(import.meta.dir, "../../..");
const args = process.argv.slice(2);
const jobs: [string, string][] = args.length ? args.map((a) => a.split("=") as [string, string]) : [];
if (!jobs.length) {
  for (const [name, m] of Object.entries(MODELS)) jobs.push([name, join(ROOT, "assets/media", name, m.file)]);
}
const out: Record<string, Silhouette> = {};
const genPath = join(import.meta.dir, "silhouettes.gen.ts");
// Keep the tables of models this run does not draw again.
Object.assign(out, SILHOUETTES);
for (const [name, file] of jobs) {
  const bytes = new Uint8Array(readFileSync(file));
  const t0 = Date.now();
  out[name] = silhouetteOfGlb(bytes, gltfBounds(gltfJson(bytes)));
  const front = viewAt(out[name]!, 0, 15);
  console.log(`${name}: ${Date.now() - t0} ms; from the front it covers ${(front[0]! * 100).toFixed(1)} % of its square; densest point ${out[name]!.dense.map((v) => v.toFixed(2)).join(", ")}`);
}
const body = Object.entries(out).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(genPath, `// Generated by src/system/three/make_silhouettes.ts. Do not edit: run \`bun src/system/three/make_silhouettes.ts\` again.\n// Each model's silhouette from ${YAWS} yaws and ${PITCHES.length} pitches (see silhouette.ts).\nimport type { Silhouette } from "./silhouette";\n\nexport const SILHOUETTES: Record<string, Silhouette> = {\n${body}\n};\n`);
console.log(`wrote ${genPath}`);
