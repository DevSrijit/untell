/** The film's own source: the module's direct import whose file name ends the film id (reel-console: console.ts), or else
 *  all of the module's direct imports. */
function sourcesOf(id: string, deep = false): string[] {
  // A HyperFrames film: its page and the bundle that holds the scene.
  const hf = HF_PAGES.get(id);
  if (hf) {
    // The scene the page was built from (hf_check and untell render write untell-scene.json): its declarations count.
    const meta = join(dirname(hf), "untell-scene.json");
    const scene = existsSync(meta) ? (JSON.parse(readFileSync(meta, "utf8")) as { scene?: string }).scene : undefined;
    return [hf, join(dirname(hf), "assets", "vs-hyperframes.js"), ...(scene ? [scene] : [])].filter((p) => existsSync(p));
  }
  const text = readFileSync(filmsModule, "utf8");
  const file = (spec: string) => [".ts", ".tsx", ""].map((ext) => resolve(dirname(filmsModule), spec + ext)).find((p) => existsSync(p) && statSync(p).isFile());
  const imports = [...text.matchAll(/from\s+"(\.[^"]+)"/g)].map((m) => m[1]!).filter((s) => !s.includes("/blocks/"));
  const own = imports.filter((s) => id.endsWith(`-${basename(s)}`) || id === basename(s));
  // No import named after the film (a module of several fixtures): every direct import counts.
  const direct = (own.length ? own : imports).map(file).filter((p): p is string => !!p);
  // Every level further, outside the kit: a fixture module that gathers others (planted.ts imports tells.ts, the agents'
  // films import drafts.ts, which imports geleth-draft.ts). One level missed a draft edit: the recording stayed stale.
  // The scene's declarations (sources.json) read one level only, so a fixture never takes another film's whole-film
  // untell-ignore; the recording's freshness (deep) reads every level.
  const seen = new Set(direct), next: string[] = [];
  for (let queue = [...direct], depth = new Map(direct.map((d) => [d, 0])); queue.length; ) {
    const d = queue.shift()!;
    for (const m of readFileSync(d, "utf8").matchAll(/from\s+"(\.[^"]+)"/g)) {
      const p = [".ts", ".tsx", ""].map((ext) => resolve(dirname(d), m[1]! + ext)).find((q) => existsSync(q) && statSync(q).isFile());
      if (!p || p.includes("/src/system/") || seen.has(p)) continue;
      seen.add(p); next.push(p);
      depth.set(p, depth.get(d)! + 1);
      if (deep) queue.push(p);
    }
  }
  return [filmsModule, ...new Set([...direct, ...next])];
}

const mtime = (p: string) => (existsSync(p) ? statSync(p).mtimeMs : 0);

/** The newest change in the kit (src/system, without tests and docs). A block draws the film too: a recording older
 *  than the kit may show the old block. The recorder then decides from its own key (the whole bundle) whether it
 *  must draw the film again; an unchanged bundle comes from its cache in a moment. */
let kitTime: number | null = null;
function kitMtime(): number {
  if (kitTime !== null) return kitTime;
  let best = 0;
  const walk = (d: string) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (/\.(ts|tsx|json)$/.test(e.name) && !/\.test\.tsx?$/.test(e.name)) best = Math.max(best, mtime(p));
    }
  };
  walk(join(ROOT, "src", "system"));
  return (kitTime = best);
}

function ensureRecording(list: string[]) {
  const stale = list.filter((id) => {
    const el = join(REC, id, "elements.json");
    // video.mp4 is optional now (record.ts --video); the frames are what the checks read. A recording past its
    // age keeps its JSON but not its frames (cache.ts, pruneRecordings): it records again.
    if (force || !existsSync(join(REC, id, "frames")) || !existsSync(el)) return true;
    // A recording that another run cut short keeps an old elements.json but lacks frames.
    const frames = readdirSync(join(REC, id, "frames")).filter((f) => f.endsWith(".jpg")).length;
    if (frames !== JSON.parse(readFileSync(el, "utf8")).durationInFrames) return true;
    // The time of the recording: its key.txt, which the recorder writes new each time it installs a recording (one
    // from its cache keeps the old elements.json time, as the files are hard links).
    const key = join(REC, id, "key.txt");
    // elements.json written well after key.txt: a single-frame recording (record.ts --at) wrote some frames of another
    // state into this folder. The frames then mix two states: record the film again.
    if (existsSync(key) && mtime(el) > mtime(key) + 2000) return true;
    const recorded = Math.max(mtime(el), mtime(key));
    return Math.max(...sourcesOf(id, true).map(mtime), HF_PAGES.has(id) ? 0 : kitMtime()) > recorded;
  });
  if (!stale.length) return;
  log(`recording ${stale.join(", ")}`);
  const films = stale.filter((id) => !HF_PAGES.has(id)), pages = stale.filter((id) => HF_PAGES.has(id)).map((id) => `hf:${HF_PAGES.get(id)}`);
  for (const argv of [films.length ? ["--films", filmsModule, ...films] : [], pages]) {
    if (!argv.length) continue;
    // The recorder shares work: it waits for another run that records the same film (a lock per film), and an
    // unchanged film comes from its cache. So two tools that need one film at once record it once.
    const r = spawnSync("bun", [join(ROOT, "scripts/record.ts"), "--force", ...(noCache ? ["--no-cache"] : []), ...argv], { cwd: ROOT, encoding: "utf8", timeout: 3600000 });
    if (r.status !== 0) { log(r.stdout.slice(-3000), r.stderr.slice(-3000)); throw new Error("recording failed"); }
  }
}

// ---------- 2. Capture: nodes and ink ----------

// Runs in the page after each seek: the ink of every text element, from the font's glyph metrics, with the
// same element ids as elements.json. Every frame: the union ink box and the cap and x heights. Each letter's ink
// box on the sampled frames (withLetters) and whenever the text's ink changed since its letters last went out.
const inkSample = (withLetters: boolean) => {
  const root = document.getElementById("root")!;
  const visibleRect = (el: Element) => {
    const r = el.getBoundingClientRect();
    let x0 = r.left, y0 = r.top, x1 = r.right, y1 = r.bottom;
    for (let e = el.parentElement; e && e !== root; e = e.parentElement) {
      const cs = getComputedStyle(e);
      const clipsX = cs.overflowX === "hidden" || cs.overflowX === "clip", clipsY = cs.overflowY === "hidden" || cs.overflowY === "clip";
      if (!clipsX && !clipsY) continue;
      const a = e.getBoundingClientRect();
      if (a.left <= 0.5 && a.top <= 0.5 && a.right >= innerWidth - 0.5 && a.bottom >= innerHeight - 0.5) continue;
      if (clipsX) { x0 = Math.max(x0, a.left); x1 = Math.min(x1, a.right); }
      if (clipsY) { y0 = Math.max(y0, a.top); y1 = Math.min(y1, a.bottom); }
    }
    return { left: x0, top: y0, right: Math.max(x0, x1), bottom: Math.max(y0, y1) };
  };
  const labelEl = (el: Element): Element | null => {
    for (let e: Element | null = el; e && e !== root; e = e.parentElement) {
      const v = e.getAttribute("data-el");
      if (v && ((v !== "ground" && v !== "texture" && v !== "world") || e === el)) return e;
    }
    return null;
  };
  const pathOf = (el: Element) => {
    const parts: string[] = [];
    for (let e: Element | null = el; e && e !== root; e = e.parentElement) {
      parts.unshift(`${e.tagName.toLowerCase()}${e.parentElement ? Array.from(e.parentElement.children).indexOf(e) : 0}`);
    }
    return parts.join("/");
  };
  const pen = document.createElement("canvas").getContext("2d")!;
  const out: unknown[] = [];
  for (const el of Array.from(root.querySelectorAll<HTMLElement>("*"))) {
    const nodes = Array.from(el.childNodes).filter((n) => n.nodeType === 3 && (n.textContent ?? "").trim());
    if (!nodes.length) continue;
    const cs = getComputedStyle(el);
    if (cs.display === "none" || cs.visibility === "hidden") continue;
    let opacity = 1;
    for (let e: Element | null = el; e && e !== root; e = e.parentElement) opacity *= Number(getComputedStyle(e).opacity);
    if (opacity < 0.02) continue;
    const clip = visibleRect(el);
    if (clip.right - clip.left < 0.5 || clip.bottom - clip.top < 0.5) continue;
    pen.font = `${cs.fontStyle} ${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`;
    const up = cs.textTransform === "uppercase", low = cs.textTransform === "lowercase";
    const tabular = /tabular/.test(cs.fontVariantNumeric ?? "");
    const spacing = (parseFloat(cs.letterSpacing) || 0) * (el.offsetHeight ? el.getBoundingClientRect().height / el.offsetHeight : 1);
    const offH = el.offsetHeight;
    const scale = offH ? el.getBoundingClientRect().height / offH : 1;
    const cap = pen.measureText("H").actualBoundingBoxAscent * scale;
    const xh = pen.measureText("x").actualBoundingBoxAscent * scale;
    let u = [Infinity, Infinity, -Infinity, -Infinity];
    // The ink before any clip (raw), and whether a clip (overflow, clip-path or mask) cut or hid a letter.
    let raw = [Infinity, Infinity, -Infinity, -Infinity], cut = false;
    const letters: number[][] = [];
    // The baseline of the first letter (from the font's ascent in its range box): the align/* checks read it.
    let firstBase: number | null = null;
    for (const node of nodes) {
      const str = node.textContent ?? "";
      for (let i = 0; i < str.length; i++) {
        let ch = str[i]!;
        if (!ch.trim()) continue;
        if (up) ch = ch.toUpperCase(); else if (low) ch = ch.toLowerCase();
        const range = document.createRange();
        range.setStart(node, i); range.setEnd(node, i + 1);
        const rc = range.getBoundingClientRect();
        const m = pen.measureText(ch);
        const k = rc.height / (m.fontBoundingBoxAscent + m.fontBoundingBoxDescent || 1);
        const base = rc.top + m.fontBoundingBoxAscent * k;
        firstBase ??= base;
        // The canvas measures a digit's proportional glyph; with tabular figures (every kit text sets tabular-nums) the
        // page draws a glyph of the same shape centred in a wider advance. So a digit's ink keeps its offset from the
        // centre of its own advance, moved to the centre of the tabular advance (the range's width without tracking).
        // Without this, a "0" read 3-6 px past its right edge, and a clip at the true edge read as a cut.
        let left = rc.left;
        if (tabular && ch >= "0" && ch <= "9") left = rc.left + (rc.width - spacing - m.width * k) / 2;
        const b = [left - m.actualBoundingBoxLeft * k, base - m.actualBoundingBoxAscent * k, left + m.actualBoundingBoxRight * k, base + m.actualBoundingBoxDescent * k];
        const c = [Math.max(b[0]!, clip.left), Math.max(b[1]!, clip.top), Math.min(b[2]!, clip.right), Math.min(b[3]!, clip.bottom)];
        raw = [Math.min(raw[0]!, b[0]!), Math.min(raw[1]!, b[1]!), Math.max(raw[2]!, b[2]!), Math.max(raw[3]!, b[3]!)];
        if (c.some((v, j) => Math.abs(v - b[j]!) > 0.5)) cut = true;
        if (c[2]! - c[0]! < 0.5 || c[3]! - c[1]! < 0.5) continue;
        u = [Math.min(u[0]!, c[0]!), Math.min(u[1]!, c[1]!), Math.max(u[2]!, c[2]!), Math.max(u[3]!, c[3]!)];
        letters.push([ch.codePointAt(0)!, ...c.map((v) => Math.round(v * 10) / 10)]);
      }
    }
    if (!Number.isFinite(u[0]!)) continue;
    const label = labelEl(el)?.getAttribute("data-el");
    // Letters go out on the sampled frames and on every frame where this text's ink moved since its letters
    // last went out, so a short crossing is not missed; between, the checks carry the last letters forward.
    const lw = window as unknown as { __lettersAt?: Map<string, string> };
    lw.__lettersAt ??= new Map();
    const ownKey = `${label ?? ""}|${pathOf(el)}`, inkKey = u.map((v) => Math.round(v * 10)).join(",");
    const sendLetters = withLetters || lw.__lettersAt.get(ownKey) !== inkKey;
    if (sendLetters) lw.__lettersAt.set(ownKey, inkKey);
    let bg: string | null = null;
    for (let e: HTMLElement | null = el; e; e = e.parentElement) {
      const b = getComputedStyle(e).backgroundColor;
      if (b && b !== "rgba(0, 0, 0, 0)" && b !== "transparent") { bg = b; break; }
    }
    // A clip-path or a mask on the text or a box round it (a wipe), and a blend (mix-blend-mode) that changes its drawn colour.
    let masked = false, blend: string | null = null;
    for (let e: Element | null = el; e && e !== root; e = e.parentElement) {
      const es = getComputedStyle(e) as CSSStyleDeclaration & { webkitMaskImage?: string };
      if ((es.clipPath && es.clipPath !== "none") || (es.maskImage && es.maskImage !== "none") || (es.webkitMaskImage && es.webkitMaskImage !== "none")) masked = true;
      if (!blend && es.mixBlendMode && es.mixBlendMode !== "normal") blend = es.mixBlendMode;
    }
    // CSS truncation: text-overflow ellipsis with the text wider than its box (the "…" is not in the DOM text).
    const ellipsis = cs.textOverflow === "ellipsis" && el.scrollWidth > el.clientWidth + 0.5;
    // What the text holds, as the renderer marks it (data-content on the node: "code" or "data"); density reads it.
    const content = el.closest("[data-content]")?.getAttribute("data-content") ?? null;
    out.push({
      id: label && label !== "ground" && label !== "texture" ? `${label}:${pathOf(el)}` : label ?? pathOf(el),
      node: label ?? null,
      text: nodes.map((n) => n.textContent).join("").trim().slice(0, 80),
      role: el.closest("[data-role]")?.getAttribute("data-role") ?? null,
      ink: u.map((v) => Math.round(v * 10) / 10), base: firstBase === null ? null : Math.round(firstBase * 10) / 10, cap: Math.round(cap * 10) / 10, xh: Math.round(xh * 10) / 10,
      fontPx: Math.round(parseFloat(cs.fontSize) * scale * 10) / 10, color: cs.color, opacity: Math.round(opacity * 1000) / 1000, plate: bg,
      ...(sendLetters ? { letters } : {}),
      ...(cut || masked ? { clipped: true, raw: raw.map((v) => Math.round(v * 10) / 10) } : {}),
      ...(blend ? { blend } : {}), ...(ellipsis ? { ellipsis: true } : {}), ...(content ? { content } : {}),
    });
  }
  return out;
};


// Runs in the page after each seek: the painted geometry of every visible SVG shape (path, circle, line, rect,
// polyline, polygon, ellipse) in screen px, for the text-crossed check. A stroke is a polyline sampled every 4 px
// along the shape (getPointAtLength, mapped through getScreenCTM), cut to the part a "draw" reveal shows. A fill is
// its screen box. Points round to 0.5 px. Each geometry is stored once in a table and frames refer to it by index.
// `m` is the shape's screen matrix (a b c d e f): where a point of the scene's own coordinates is painted, so a check can
// follow a named point of a part (the joint check: a load on a beam's end) through the render.
const shapeSample = () => {
  const root = document.getElementById("root")!;
  const w = window as unknown as { __geomKey?: Map<string, number>; __geoms?: number[][][] ; __shapeCache?: Map<string, { key: string; pts: number[][] }> };
  w.__geomKey ??= new Map(); w.__geoms ??= []; w.__shapeCache ??= new Map();
  const out: unknown[] = [];
  const clear = (c: string | null) => !c || c === "none" || c === "transparent" || c === "rgba(0, 0, 0, 0)";
  for (const el of Array.from(root.querySelectorAll<SVGGeometryElement>("svg path, svg circle, svg line, svg rect, svg polyline, svg polygon, svg ellipse"))) {
    if (el.closest("mask, clipPath, defs")) continue;
    const cs = getComputedStyle(el);
    if (cs.display === "none" || cs.visibility === "hidden") continue;
    let opacity = 1;
    for (let e: Element | null = el; e && e !== root; e = e.parentElement) opacity *= Number(getComputedStyle(e).opacity);
    if (opacity < 0.1) continue;
    const layer = el.closest("[data-el]")?.getAttribute("data-el") ?? "";
    let label = "";
    for (let e: Element | null = el; e && e !== root; e = e.parentElement) {
      const v = e.getAttribute("data-el");
      if (v && !/^scene-shapes/.test(v)) { label = v; break; }
    }
    if (!label || label === "ground" || label === "texture") continue;
    const ctm = el.getScreenCTM();
    if (!ctm) continue;
    const stroke = clear(cs.stroke) || parseFloat(cs.strokeWidth) <= 0 ? null : cs.stroke;
    const fill = clear(cs.fill) ? null : cs.fill;
    const scale = Math.hypot(ctm.a, ctm.b);
    const r = el.getBoundingClientRect();
    const item: Record<string, unknown> = { id: label, layer, opacity: Math.round(opacity * 100) / 100,
      box: [r.left, r.top, r.right, r.bottom].map((v) => Math.round(v * 2) / 2),
      m: [ctm.a, ctm.b, ctm.c, ctm.d].map((v) => Math.round(v * 1e4) / 1e4).concat([ctm.e, ctm.f].map((v) => Math.round(v * 100) / 100)) };
    if (fill) item.fill = fill;
    if (stroke) {
      // The part a reveal shows: pathLength 1 with dasharray "1 1" draws 1 - dashoffset of the path from its start.
      let shown = 1;
      const masked = el.getAttribute("mask");
      const src = masked ? document.querySelector(`${masked.slice(4, -1)} path`) : el;
      if (src && src.getAttribute("pathLength") === "1" && /^1[ ,]+1$/.test((src.getAttribute("stroke-dasharray") ?? "").trim()))
        shown = Math.max(0, Math.min(1, 1 - Number(src.getAttribute("stroke-dashoffset") ?? 0)));
      const key = `${el.getAttribute("d") ?? el.outerHTML.slice(0, 200)}|${ctm.a},${ctm.b},${ctm.c},${ctm.d},${ctm.e},${ctm.f}|${shown}`;
      let pts = w.__shapeCache.get(label + "#" + key)?.pts;
      if (!pts) {
        pts = [];
        let len = 0;
        try { len = el.getTotalLength(); } catch { len = 0; }
        const stepUser = 4 / (scale || 1);
        const end = len * shown;
        for (let d = 0; d <= end + 1e-6 && len > 0; d += stepUser) {
          const p = el.getPointAtLength(Math.min(d, end));
          pts.push([Math.round((ctm.a * p.x + ctm.c * p.y + ctm.e) * 2) / 2, Math.round((ctm.b * p.x + ctm.d * p.y + ctm.f) * 2) / 2]);
          if (pts.length > 4000) break;
        }
        w.__shapeCache.set(label + "#" + key, { key, pts });
      }
      const gk = JSON.stringify(pts);
      let gi = w.__geomKey.get(gk);
      if (gi === undefined) { gi = w.__geoms.length; w.__geoms.push(pts); w.__geomKey.set(gk, gi); }
      item.stroke = stroke; item.width = Math.round(parseFloat(cs.strokeWidth) * scale * 10) / 10; item.g = gi;
    }
    if (!item.stroke && !item.fill) continue;
    out.push(item);
  }
  return out;
};

