type Finding = { check: string; severity: "error" | "warning"; from: number; to: number; node?: string; measured: unknown; limit: unknown; fix: string };

type Group = { check: string; severity: string; cause: string; title?: string; count: number; likelyGoneAfterFix: number; from: number; to: number; nodes: string[]; fix: string };
type Declared = Finding & { declared: { reason: string; where: string; scope: string } };
type Verdict = { state: "passed" | "warnings" | "failed"; errors: number; warnings: number; advice: number; unusedDeclarations?: number; renderStale: boolean; line: string };
type Declaration = { rule: string; nodes: string[]; matched: number; effect?: string; why?: string; where: string };
type Result = { film: string; system: string | null; findings: Finding[]; skipped: Record<string, string>; groups?: Group[]; declared?: Declared[]; verdict?: Verdict; declarations?: Declaration[] };

/** Runs every check on one film in its own Python process. */
async function runChecks(id: string): Promise<Result> {
  // The checks are CPU work too: they take a machine slot like every other untell tool.
  const release = await slot(`detect checks ${id}`, log);
  // With other folders (UNTELL_DET_OUT, UNTELL_REC_OUT), the same checks run through scripts/perf/run_detect_py.py.
  const moved = process.env.UNTELL_DET_OUT || process.env.UNTELL_REC_OUT;
  const p = Bun.spawn(moved ? ["python3", join(ROOT, "scripts/perf/run_detect_py.py"), id, "--rec", REC, "--det", OUT] : ["python3", join(ROOT, "scripts/inspect/detect.py"), id], { cwd: ROOT, stdout: "pipe", stderr: "pipe" });
  const [out, err, code] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text(), p.exited]).finally(release);
  if (code !== 0) { log(err.slice(-4000)); throw new Error(`checks failed for ${id}`); }
  if (err.trim()) log(err.trim());
  return JSON.parse(out);
}

function sameness(list: string[]) {
  const r = spawnSync("python3", [join(ROOT, "scripts/inspect/checks/sameness.py"), ...list], { cwd: ROOT, encoding: "utf8", timeout: 1200000 });
  if (r.status !== 0) { log(r.stderr.slice(-4000)); throw new Error("sameness failed"); }
  return JSON.parse(r.stdout) as { films: string[]; findings: Finding[] };
}

// The first screen (out/readme/check-screen.md, the same as untell check prints): marks are characters (x an error, !
// a warning, i advice, = declared, - not run; a pass is the word "passed"); colour only on a terminal, never with NO_COLOR.
const tty = process.stdout.isTTY && !process.env.NO_COLOR;
const paint = (code: string) => (s: string) => (tty ? `\x1b[${code}m${s}\x1b[0m` : s);
const red = paint("31"), yellow = paint("33"), green = paint("32"), dim = paint("2"), bold = paint("1");
const mark = (sev: string) => (sev === "error" ? red("x") : sev === "warning" ? yellow("!") : dim("i"));
const span = (a: number, b: number) => (a === b ? `${a.toFixed(2)} s` : `${a.toFixed(2)}–${b.toFixed(2)} s`);
const fmt = (f: Finding) =>
  `  ${mark(f.severity)} ${f.check.padEnd(22)} ${span(f.from, f.to).padEnd(13)} ${f.node ?? ""}`.trimEnd() +
  `\n      ${dim(`measured ${JSON.stringify(f.measured)} · limit ${JSON.stringify(f.limit)}`)}`;

