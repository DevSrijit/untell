// A HyperFrames page, opened as scripts/record.ts opens it: the runtime injected first (as HyperFrames' renderer does),
// then __seek through the runtime's renderSeek. An init script also wraps VS.scene, so the scene's nodes reach
// window.__nodes as they do on the Remotion capture page. The DOM of a node is the same in both renderers.
let HF_RUNTIME = process.env.HF_RUNTIME ?? join(ROOT, "node_modules/hyperframes/dist/hyperframe.runtime.iife.js");
const hfReady = new WeakSet<Page>();
async function openHf(page: Page, file: string) {
  if (!hfReady.has(page)) {
    if (existsSync(HF_RUNTIME)) await page.addInitScript({ path: HF_RUNTIME });
    else log(`no HyperFrames runtime at ${HF_RUNTIME} (set HF_RUNTIME): seeking the GSAP timeline alone`);
    await page.addInitScript(() => {
      let vs: Record<string, unknown> | undefined;
      Object.defineProperty(window, "VS", { configurable: true, get: () => vs, set: (v: Record<string, unknown>) => {
        vs = v;
        let scene: unknown;
        Object.defineProperty(v, "scene", { configurable: true, get: () => scene, set: (fn: (ctx: { safe: unknown; width: number; height: number }, B: unknown) => unknown) => {
          scene = (ctx: { safe: unknown; width: number; height: number }, B: unknown) => {
            // The blocks' warnings, as on the Remotion capture page.
            const said: string[] = [], warn = console.warn;
            console.warn = (...m: unknown[]) => { said.push(m.map(String).join(" ")); warn(...m); };
            let nodes: unknown;
            try { nodes = fn(ctx, B); } finally { console.warn = warn; }
            (window as unknown as { __warnings: string[] }).__warnings = said;
            (window as unknown as { __nodes: unknown }).__nodes = JSON.parse(JSON.stringify(nodes));
            (window as unknown as { __ctx: unknown }).__ctx = { safe: ctx.safe, width: ctx.width, height: ctx.height };
            return nodes;
          };
        } });
      } });
    });
    hfReady.add(page);
  }
  await page.goto(`file://${file}`);
  await page.waitForFunction((rt) => !!(window as unknown as { __timelines?: Record<string, unknown> }).__timelines?.main &&
    (!rt || (window as unknown as { __renderReady?: boolean }).__renderReady === true), existsSync(HF_RUNTIME), { timeout: 20000, polling: 100 });
  await page.evaluate(async () => {
    await document.fonts.ready;
    const root = document.querySelector("[data-composition-id]")!;
    const fps = 30;
    const n = (k: string) => Number(root.getAttribute(k));
    const w = window as unknown as { __meta: unknown; __seek: (f: number) => Promise<void>; __timelines: Record<string, { seek: (t: number, s: boolean) => void }> };
    w.__meta = { fps, width: n("data-width"), height: n("data-height"), durationInFrames: Math.round(n("data-duration") * fps) };
    const hf = window as unknown as { __player?: { renderSeek?: (t: number) => void; enableRenderMode?: () => void }; __hfWaitForSeekCompletion?: () => Promise<void> };
    const viaRuntime = typeof hf.__player?.renderSeek === "function";
    if (viaRuntime) hf.__player!.enableRenderMode?.();
    w.__seek = async (f: number) => {
      if (viaRuntime) { hf.__player!.renderSeek!(f / fps); await hf.__hfWaitForSeekCompletion?.(); }
      // The paused GSAP timeline is what draws the scene, as the recorder seeks it (scripts/record.ts). The runtime's
      // renderSeek alone left every tween at frame 0 in the capture: a beam that turned in the recording rested in
      // the capture, so the checks that read shapes (joint, shape-crossed, text-crossed) saw frame 0 on every frame.
      w.__timelines.main!.seek(f / fps, false);
      const waits: Promise<unknown>[] = [];
      window.dispatchEvent(new CustomEvent("hf-seek", { detail: { time: f / fps, waitUntil: (p: Promise<unknown>) => waits.push(p) } }));
      await Promise.all(waits);
      if (document.querySelector("canvas, video")) await new Promise((r) => requestAnimationFrame(() => requestAnimationFrame(r)));
    };
  });
}

async function capture(page: Page, id: string) {
  const dir = join(OUT, id);
  const file = join(dir, "capture.json");
  // The capture cache: keyed by the recording it reads (the recorder's key.txt holds all code, scene data, media
  // and browser) and by this file's own code. The same recording gives the same capture.
  // key.txt is trusted only when it is as new as elements.json: a recorder without keys (--slow) leaves an old one.
  // (A recording from the recorder's cache is hard-linked, so its elements.json keeps the old time; key.txt is new.)
  const keyFile = join(REC, id, "key.txt");
  const recKey = existsSync(keyFile) && mtime(keyFile) >= mtime(join(REC, id, "elements.json")) ? readFileSync(keyFile, "utf8").trim() : "";
  // A capture of version 7 (5: the text's data-content, the blocks' warnings, the recording's key; 7: each shape's screen matrix; 6: digits measured as
  // tabular figures) of this recording is
  // kept. With a key, the capture must name the same key: a capture of an older recording (the kit changed, the
  // recorder took the new recording from its cache) has the old one. Without a key, the capture must be newer.
  if (!force && existsSync(file)) {
    const head = readFileSync(file, "utf8").slice(0, 400);
    const same = recKey ? head.includes(`"recKey":"${recKey}"`) : mtime(file) > mtime(join(REC, id, "elements.json"));
    if (same && head.includes('"captureVersion":7')) return;
  }
  const capKey = recKey ? sha("capture-7", recKey, SELF) : "";
  const hit = capKey && !noCache ? lookup("capture", capKey) : null;
  if (hit) { mkdirSync(dir, { recursive: true }); writeFileSync(file, readFileSync(join(hit, "capture.json"))); return; }
  const hfPage = HF_PAGES.get(id);
  if (hfPage) await openHf(page, hfPage);
  else await page.goto(`file://${join(ROOT, "web", `${RUN}.html`)}?comp=${encodeURIComponent(id)}`);
  const meta = await page.evaluate(() => window.__meta);
  if (!meta) throw new Error(`no film ${id} in ${filmsModule || hfPage}`);
  await page.setViewportSize({ width: meta.width, height: meta.height });
  await page.waitForFunction(() => {
    const el = document.querySelector("[data-system]");
    return !el || el.hasAttribute("data-ready") || !!(window as unknown as { __timelines?: Record<string, unknown> }).__timelines?.main;
  }, null, { timeout: 15000, polling: 100 });
  const ink: unknown[] = [];
  const shapes: unknown[] = [];
  // A frame that the scene keys as the same as the one before needs no seek: the page already shows it. The
  // samplers still run on that DOM, so what they keep between frames (which letters went out) stays the same.
  let lastKey: string | null = null;
  for (let f = 0; f < meta.durationInFrames; f++) {
    const key = await page.evaluate((n) => (window as unknown as { __frameKey?: (f: number) => string | null }).__frameKey?.(n) ?? null, f);
    if (key === null || key !== lastKey) await page.evaluate((n) => window.__seek(n), f);
    lastKey = key;
    ink.push(await page.evaluate(inkSample, f % 15 === 0));
    shapes.push(await page.evaluate(shapeSample));
  }
  const geoms = await page.evaluate(() => (window as unknown as { __geoms?: unknown }).__geoms ?? []);
  const nodes = await page.evaluate(() => (window as unknown as { __nodes?: unknown }).__nodes ?? null);
  const ctx = await page.evaluate(() => (window as unknown as { __ctx?: unknown }).__ctx ?? null);
  const warnings = await page.evaluate(() => (window as unknown as { __warnings?: string[] }).__warnings ?? null);
  mkdirSync(dir, { recursive: true });
  const demo = await page.evaluate(() => (window as unknown as { __demo?: boolean }).__demo ?? false);
  writeFileSync(file, JSON.stringify({ captureVersion: 7, recKey, ...(demo ? { demo } : {}), renderer: hfPage ? "hyperframes" : "remotion", id, ...meta, nodes, ctx, warnings, ink, shapes: { geoms, frames: shapes } }));
  if (capKey && !noCache) {
    const tmp = join(OUT, id, `.capture-${process.pid}`);
    mkdirSync(tmp, { recursive: true });
    writeFileSync(join(tmp, "capture.json"), readFileSync(file));
    store("capture", capKey, tmp);
    rmSync(tmp, { recursive: true, force: true });
  }
}

// ---------- 3. Sound ----------

type AudioNode = { id: string; kind: "audio"; src: string; at: number; until?: number; from?: number; volume?: number; fadeIn?: number; fadeOut?: number };

// The media folders: assets/media first, then any folder a test bench adds (its registry.gen.ts lists its sounds).
const MEDIA_DIRS = [join(ROOT, "assets", "media")];
const mediaFile = (src: string) => MEDIA_DIRS.map((d) => join(d, src)).find((p) => existsSync(p)) ?? join(MEDIA_DIRS[0]!, src);

/** The facts of the sounds in the other media folders (registry.gen.ts in each), as media.gen.ts gives assets/media's. */
function extraSounds(): Record<string, { kind: string; file: string; duration: number; peak: number }> {
  const out: Record<string, { kind: string; file: string; duration: number; peak: number }> = {};
  for (const d of MEDIA_DIRS.slice(1)) {
    const p = join(d, "registry.gen.ts");
    if (!existsSync(p)) continue;
    const m = readFileSync(p, "utf8").match(/REGISTRY = (\{[\s\S]*\}) as const/);
    try { Object.assign(out, m ? JSON.parse(m[1]!).SOUNDS ?? {} : {}); } catch { /* a broken table adds nothing */ }
  }
  return out;
}

/** The film's sound, mixed as the renderers play it: each clip trimmed, faded, set to its volume and placed at its time. */
function mix(id: string, nodes: AudioNode[], seconds: number) {
  const out = join(OUT, id, "sound.wav");
  const inputs: string[] = [];
  const chains: string[] = [];
  nodes.forEach((n, i) => {
    inputs.push("-i", mediaFile(n.src));
    const len = (n.until ?? seconds) - n.at;
    const f: string[] = [`atrim=start=${n.from ?? 0}:duration=${len.toFixed(4)}`, "asetpts=PTS-STARTPTS", "aresample=48000", "aformat=channel_layouts=stereo"];
    if (n.fadeIn) f.push(`afade=t=in:st=0:d=${n.fadeIn}`);
    if (n.fadeOut) f.push(`afade=t=out:st=${Math.max(0, len - n.fadeOut).toFixed(4)}:d=${n.fadeOut}`);
    f.push(`volume=${n.volume ?? 1}`);
    const ms = Math.round(n.at * 1000);
    if (ms > 0) f.push(`adelay=${ms}|${ms}`);
    chains.push(`[${i}:a]${f.join(",")}[a${i}]`);
  });
  const filter = `${chains.join(";")};${nodes.map((_, i) => `[a${i}]`).join("")}amix=inputs=${nodes.length}:normalize=0:duration=longest,apad=whole_dur=${seconds}[out]`;
  const r = spawnSync("ffmpeg", ["-loglevel", "error", "-y", ...inputs, "-filter_complex", filter, "-map", "[out]", "-t", String(seconds), "-c:a", "pcm_s16le", out], { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], timeout: 120000 });
  if (r.status !== 0) throw new Error(`ffmpeg mix failed for ${id}: ${r.stderr}`);
  return out;
}

function hfJson(argv: string[]) {
  const r = spawnSync(HF, argv, { cwd: ROOT, env: HF_ENV, encoding: "utf8", timeout: 300000 });
  try { return JSON.parse(r.stdout); } catch { log(`hyperframes ${argv.join(" ")} failed: ${(r.stderr || r.stdout).slice(0, 400)}`); return null; }
}

/** The beat grid, downbeats and sections of a music file (cached in out/detector/beats). */
function beatsOf(src: string) {
  const file = join(OUT, "beats", `${src.replace(/[/.]/g, "_")}.json`);
  if (existsSync(file)) return JSON.parse(readFileSync(file, "utf8"));
  const media = mediaFile(src);
  const b = hfJson(["beats", "--json", media]);
  const a = hfJson(["audio", "--json", "--only", "downbeats,sections", media]);
  const item = a?.items?.[0] ?? {};
  const res = { beats: b?.beatTimes ?? [], bpm: b?.bpm ?? null, downbeats: item.downbeats?.times ?? [], sections: item.sections?.spans ?? [] };
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, JSON.stringify(res));
  return res;
}

function sound(id: string) {
  const cap = JSON.parse(readFileSync(join(OUT, id, "capture.json"), "utf8"));
  const nodes: AudioNode[] = (cap.nodes ?? []).filter((n: { kind: string }) => n.kind === "audio");
  const file = join(OUT, id, "sound.json");
  if (!nodes.length) { writeFileSync(file, JSON.stringify({ hasSound: false })); return; }
  const seconds = cap.durationInFrames / cap.fps;
  const wav = mix(id, nodes, seconds);
  const loud = hfJson(["audio", "--json", "--only", "loudness", wav])?.items?.[0]?.loudness ?? null;
  // Each clip's file facts (duration, peak) from media.gen.ts, and the beat grid of each music file.
  const gen = readFileSync(join(ROOT, "src/system/media.gen.ts"), "utf8");
  const facts: Record<string, { kind: string; peak: number; duration: number }> = {};
  for (const m of gen.matchAll(/"([^"]+)": \{ kind: "(sfx|music)", file: "([^"]+)", duration: ([\d.]+), peak: ([\d.]+)/g))
{
    facts[`${m[1]}/${m[3]}`] = { kind: m[2]!, duration: Number(m[4]), peak: Number(m[5]) };
    // music plays <name>/master.wav when the track has one (the listening layer's mastered bed): the same track.
    facts[`${m[1]}/master.wav`] = facts[`${m[1]}/${m[3]}`]!;
  }
  for (const [name, x] of Object.entries(extraSounds())) {
    facts[`${name}/${x.file}`] ??= { kind: x.kind, duration: x.duration, peak: x.peak };
    facts[`${name}/master.wav`] ??= facts[`${name}/${x.file}`]!;
  }
  const clips = nodes.map((n) => ({ ...n, fileKind: facts[n.src]?.kind ?? null, peak: facts[n.src]?.peak ?? null }));
  const beats: Record<string, unknown> = {};
  for (const c of clips) if (c.fileKind === "music" && !beats[c.src]) beats[c.src] = beatsOf(c.src);
  // The newest source of the film, so the sound check can tell a current render from a stale one.
  writeFileSync(file, JSON.stringify({ hasSound: true, wav, loudness: loud, clips, beats, sourceMtime: Math.max(...sourcesOf(id, true).map(mtime)) / 1000 }));
}

