//
// Usage: bun scripts/detect.ts <film id ...> --films <module> [--json] [--force] [--no-cache] [--table <file.md>]
//        bun scripts/detect.ts hf:<path to a HyperFrames index.html> ...   (a HyperFrames film; saved as hf-<folder>)
