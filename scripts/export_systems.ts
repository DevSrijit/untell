// Writes each design system in three forms that any framework can use:
//   systems/<id>/tokens.json  the data, with every colour resolved to hex
//   systems/<id>/tokens.css   CSS custom properties; set --short to the frame's short side
//   systems/<id>/SYSTEM.md    the instructions an agent reads before it makes a video
// and systems/README.md, the index an agent reads to choose a system. The files of one system come from the kit's
// src/system/systemDocs.ts, which untell system uses for a project's own systems too.
// Usage: bun scripts/export_systems.ts
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { DIRECTION } from "../src/system/direction";
import { SYSTEMS } from "../src/system/systems";

// The true italics: for each family, the weights of the roles a statement can take (display, headline, body) that
// have an italic file (WOFF2, Latin) in the family's Fontsource package. A face with no italic file never slants:
// the browser would slope the upright face, and the two renderers could draw it differently. A block sets one word
// in italic only where this table names the face (quote's emphasis); elsewhere it uses the system's emphasis colour.
// The table is written first, because systemDocs (fonts.json) and the renderers read it.
const slugOf = (f: string) => f.toLowerCase().replace(/ /g, "-");
const italic = new Map<string, Set<number>>();
for (const s of SYSTEMS) for (const role of ["display", "headline", "body"] as const) {
  const t = s.type[role], family = s.fonts[t.font] ?? s.fonts.text;
  if (!family || !existsSync(`node_modules/@fontsource/${slugOf(family)}/files/${slugOf(family)}-latin-${t.weight}-italic.woff2`)) continue;
  italic.set(family, (italic.get(family) ?? new Set<number>()).add(t.weight));
}
const ITALIC_TABLE = Object.fromEntries([...italic].sort((a, b) => a[0].localeCompare(b[0])).map(([f, ws]) => [f, [...ws].sort((a, b) => a - b)]));
writeFileSync("src/system/italics.gen.ts", `// Generated by scripts/export_systems.ts. Do not edit.
// The true italic faces the kit ships: for each family, the weights that have an italic font file (WOFF2, Latin), for
// the roles a statement can take (display, headline, body). A face that is not here has no italic: never slant it.
export const ITALIC: Record<string, number[]> = ${JSON.stringify(ITALIC_TABLE)};
`);
const { END_KIND, fontList, systemFiles } = await import("../src/system/systemDocs");
const { ITALIC } = await import("../src/system/italics.gen");
if (JSON.stringify(ITALIC) !== JSON.stringify(ITALIC_TABLE)) throw new Error("src/system/italics.gen.ts changed while this script ran: run bun scripts/export_systems.ts again");

mkdirSync("systems", { recursive: true });
const index: string[] = [];
for (const s of SYSTEMS) {
  const dir = `systems/${s.id}`;
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of Object.entries(systemFiles(s))) writeFileSync(`${dir}/${name}`, text);
  index.push(`| [${s.name}](${s.id}/SYSTEM.md) | ${s.mode} | ${s.kinds.join(", ")} | ${s.personality} |`);
}
// The ends table in systems/playbooks/craft.md: how each system ends and the block that does it, from direction.ts.
{
  const craft = "systems/playbooks/craft.md";
  const text = existsSync(craft) ? readFileSync(craft, "utf8") : "";
  const a = text.indexOf("<!-- untell:ends"), b = text.indexOf("<!-- /untell:ends -->");
  if (a >= 0 && b > a) {
    const head = text.slice(a, text.indexOf("-->", a) + 3);
    const rows = SYSTEMS.map((s) => { const e = DIRECTION[s.id]!.ends; return `| ${s.name} | ${END_KIND[e.kind]}${e.hold ? `, held ${e.hold} s` : ", no hold"}${e.onBar ? ", on a bar" : ""} | \`${e.block}\` | ${e.with} |`; });
    const table = ["", "| System | The end | Block | How |", "| --- | --- | --- | --- |", ...rows, ""].join("\n");
    writeFileSync(craft, text.slice(0, a) + head + "\n" + table + "\n" + text.slice(b));
  }
}

writeFileSync("systems/README.md", `# Design systems

Choose one system for a video. Then read its \`SYSTEM.md\` and use only what it names.
Ten systems are light and ten are dark.

## Choose by purpose and tone, not by subject

A technical subject does not need a technical system. An explainer about HTTPS can be calm and exact
(Studio), printed and warm (Riso), friendly (Pop) or engineered (Schematic). Ask three questions:

1. **What is the video for?** Use the "Use it for" column: a launch, a kinetic lyric, a quote card, a tutorial.
2. **How should the viewer feel?** Calm and premium (Studio, Keynote, Ma, Nocturne), exact and technical
   (Spec, Schematic, Graphite, Console), loud and fast (Kinetic, Courtside, Raw), warm and made by hand
   (Riso, Cutout, Primary), friendly (Pop), cinematic (Noir, Title, Matte).
3. **Light or dark?** Half the systems are each. A feed full of dark explainers makes a light one stand out.

When two systems fit, take the one the brief would not expect. Write your reason in one sentence.

| System | Mode | Use it for | Character |
| --- | --- | --- | --- |
${index.join("\n")}
`);
console.log(`wrote ${SYSTEMS.length} systems to systems/`);

// The Remotion font loaders. Each family loads its own font files (WOFF2, Latin, one file per weight, normal style)
// through the bundler, so a check and a render make no network request for a font. The repository imports the files
// from its Fontsource packages; the pack rewrites each import to the kit's fonts folder (marker "untell:pack font").
// The Latin file of Noto Sans Math holds the symbols that the fallback exists for (π, ≈, →, ←, ²).
const used = new Map<string, Set<number>>();
for (const s of SYSTEMS) for (const f of fontList(s)) {
  const have = used.get(f.family) ?? new Set<number>();
  for (const w of f.weights) have.add(w);
  used.set(f.family, have);
}
const families = [...used.keys()].sort();
const fileVar = (f: string, w: number, style = "normal") => `${slugOf(f).replace(/-/g, "_")}_${w}${style === "italic" ? "_italic" : ""}`;
const imports: string[] = [];
for (const f of families) for (const w of [...used.get(f)!].sort((a, b) => a - b)) for (const style of ["normal", ...(ITALIC[f]?.includes(w) ? ["italic"] : [])]) {
  const file = `${slugOf(f)}-latin-${w}-${style}.woff2`;
  if (!existsSync(`node_modules/@fontsource/${slugOf(f)}/files/${file}`)) throw new Error(`missing node_modules/@fontsource/${slugOf(f)}/files/${file}: bun add -d @fontsource/${slugOf(f)}`);
  imports.push(`import ${fileVar(f, w, style)} from "@fontsource/${slugOf(f)}/files/${file}"; // untell:pack font`);
}
const table = (f: string, ws: number[], style: string) => `{ ${ws.map((w) => `${w}: ${fileVar(f, w, style)}`).join(", ")} }`;
writeFileSync("src/system/fonts.gen.ts", `// Generated by scripts/export_systems.ts. Do not edit.
// The fonts of every system, from local files: WOFF2, Latin, one file per weight, normal style, and the true italic of
// a face where italics.gen.ts names it. The bundler gives each file a URL beside the page, so the fonts load with no
// network request, in a check and in a render.
${imports.join("\n")}

export type FontLoader = (style?: "normal", options?: { weights?: string[]; subsets?: string[] }) => { fontFamily: string; waitUntilDone: () => Promise<unknown> };

/** A loader for one family: it adds a FontFace for each weight asked for, from that weight's file, and the weight's
 *  italic face when the family has one (italics.gen.ts). */
const local = (family: string, files: Record<number, string>, italics: Record<number, string> = {}): FontLoader => (_style, options) => {
  const weights = (options?.weights ?? Object.keys(files)).map(Number);
  const faces = weights.flatMap((w) => {
    const url = files[w];
    if (!url) throw new Error(\`No font file for \${family} \${w}: the kit has \${Object.keys(files).join(", ")}. Use one of those weights, or add the file (WOFF2, Latin, normal style) and its import here.\`);
    const face = new FontFace(family, \`url("\${url}") format("woff2")\`, { weight: String(w), style: "normal" });
    document.fonts.add(face);
    const it = italics[w];
    if (!it) return [face];
    const slant = new FontFace(family, \`url("\${it}") format("woff2")\`, { weight: String(w), style: "italic" });
    document.fonts.add(slant);
    return [face, slant];
  });
  return { fontFamily: family, waitUntilDone: () => Promise.all(faces.map((f) => f.load())) };
};

export const FONT_LOADERS: Record<string, FontLoader> = {
${families.map((f) => { const ws = [...used.get(f)!].sort((a, b) => a - b), it = ws.filter((w) => ITALIC[f]?.includes(w)); return `  ${JSON.stringify(f)}: local(${JSON.stringify(f)}, ${table(f, ws, "normal")}${it.length ? `, ${table(f, it, "italic")}` : ""}),`; }).join("\n")}
};
`);
console.log(`wrote src/system/fonts.gen.ts (${families.length} families, ${imports.length} files) and src/system/italics.gen.ts (${Object.values(ITALIC).flat().length} italic faces)`);
