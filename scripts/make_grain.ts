// Makes the grain tiles that both renderers draw over a system with grain (see GRAIN_TILES in
// src/system/scene/layout.ts). The noise is deterministic: a fixed seed per tile, so a run always
// writes the same bytes.
//
// Writes:
// - src/system/grain/grain-<n>.png: 8 tiles, 128 x 128 px, 8-bit grey, uniform noise from 0 to 255.
//   scripts/hf_project.ts copies them into a HyperFrames project (assets/grain).
// - src/system/grain/tiles.gen.ts: the same PNG bytes as data URIs, for the Remotion renderer, which
//   has no folder of static files.
//
// Usage: bun scripts/make_grain.ts
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { deflateSync } from "node:zlib";

const ROOT = resolve(import.meta.dir, "..");
const DIR = join(ROOT, "src/system/grain");
const TILES = 8, SIZE = 128;

/** mulberry32: a small seeded random number generator. */
function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf: Uint8Array) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff]! ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type: string, data: Uint8Array) {
  const out = new Uint8Array(12 + data.length);
  const v = new DataView(out.buffer);
  v.setUint32(0, data.length);
  out.set(new TextEncoder().encode(type), 4);
  out.set(data, 8);
  v.setUint32(8 + data.length, crc32(out.subarray(4, 8 + data.length)));
  return out;
}

/** A grey PNG (colour type 0, 8 bits) from rows of bytes. */
function png(w: number, h: number, px: Uint8Array) {
  const ihdr = new Uint8Array(13);
  const v = new DataView(ihdr.buffer);
  v.setUint32(0, w); v.setUint32(4, h);
  ihdr.set([8, 0, 0, 0, 0], 8);
  const raw = new Uint8Array(h * (w + 1));
  for (let y = 0; y < h; y++) raw.set(px.subarray(y * w, (y + 1) * w), y * (w + 1) + 1); // filter 0 per row
  const parts = [new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]), chunk("IHDR", ihdr), chunk("IDAT", deflateSync(raw, { level: 9 })), chunk("IEND", new Uint8Array())];
  const out = new Uint8Array(parts.reduce((a, p) => a + p.length, 0));
  let o = 0;
  for (const p of parts) { out.set(p, o); o += p.length; }
  return out;
}

mkdirSync(DIR, { recursive: true });
const uris: string[] = [];
for (let n = 0; n < TILES; n++) {
  const r = rng(0x9e3779b9 + n * 7919);
  const px = new Uint8Array(SIZE * SIZE).map(() => Math.floor(r() * 256));
  const bytes = png(SIZE, SIZE, px);
  writeFileSync(join(DIR, `grain-${n}.png`), bytes);
  uris.push(`data:image/png;base64,${Buffer.from(bytes).toString("base64")}`);
}
writeFileSync(join(DIR, "tiles.gen.ts"), `// Generated by scripts/make_grain.ts. Do not edit.
// The grain tiles (src/system/grain/grain-<n>.png) as data URIs, for the Remotion renderer.
export const GRAIN_URIS: string[] = ${JSON.stringify(uris, null, 1)};
`);
console.log(`wrote ${TILES} grain tiles (${SIZE} px) and tiles.gen.ts to ${DIR}`);
