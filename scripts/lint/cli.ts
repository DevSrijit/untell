// untell lint: finds the tells in video source code before any frame is rendered.
//
//   bun scripts/lint/cli.ts <file or folder>...   lint files (.ts .tsx .js .jsx .html .css)
//   --json            one JSON document on stdout
//   --rules           list every rule with why and fix
//   --explain <id>    one rule in full
//   --scope any|scene treat every file as plain video code, or as an untell scene
//   --max-warnings n  exit 1 when there are more than n warnings (errors always exit 1)
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { lint, RULES, type Finding } from "./rules";

const args = process.argv.slice(2);
const flag = (n: string) => args.includes(n);
const opt = (n: string) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
const tty = process.stdout.isTTY && !process.env.NO_COLOR;
const c = (code: number, s: string) => (tty ? `\x1b[${code}m${s}\x1b[0m` : s);

if (flag("--rules")) {
  for (const r of RULES) console.log(`${c(1, r.id.padEnd(26))} ${r.severity.padEnd(8)} ${r.why}`);
  console.log(`\n${RULES.length} rules. untell lint --explain <id> shows the fix.`);
  process.exit(0);
}
if (flag("--docs")) {
  // The rule catalog as Markdown (docs/TELLS.md): one table per rule set, generated from the rules themselves.
  const table = (scope: "any" | "scene") => ["| Rule | Level | Why it is a tell | Fix |", "| --- | --- | --- | --- |",
    ...RULES.filter((r) => r.scope === scope).map((r) => `| \`${r.id}\` | ${r.severity} | ${r.why} | ${r.fix} |`)].join("\n");
  console.log(`# The tells\n\nGenerated by \`untell lint --docs\`. Do not edit.\n\n\`untell lint <files>\` reads source code and finds what makes a video read as AI-made, before any frame is rendered.\nSilence one line with \`// untell-ignore <rule id>: <reason>\`.\n\n## In any video code (Remotion, HyperFrames, HTML, CSS, GSAP)\n\n${table("any")}\n\n## In an untell scene\n\n${table("scene")}\n`);
  process.exit(0);
}
if (opt("--explain")) {
  const r = RULES.find((x) => x.id === opt("--explain"));
  if (!r) { console.error(`no rule "${opt("--explain")}". untell lint --rules lists them.`); process.exit(2); }
  console.log(`${c(1, r.id)}  (${r.severity}, ${r.scope === "scene" ? "untell scenes" : "any video code"})\n\nWhy: ${r.why}\nFix: ${r.fix}\n\nSilence one line: // untell-ignore ${r.id}: <reason>`);
  process.exit(0);
}

const skip = new Set(["--scope", "--max-warnings", "--explain"]);
const targets = args.filter((a, i) => !a.startsWith("--") && !skip.has(args[i - 1] ?? ""));
if (!targets.length) { console.error("usage: untell lint <file or folder>... [--json] [--rules] [--explain <id>] [--scope any|scene]"); process.exit(2); }
const EXT = /\.(tsx?|jsx?|html?|css)$/;
const walk = (p: string): string[] => statSync(p).isDirectory()
  ? readdirSync(p).filter((n) => !/^(node_modules|dist|out|\.git|\.untell|\.venv-media)$/.test(n) && !n.endsWith(".gen.ts")).flatMap((n) => walk(join(p, n)))
  : EXT.test(p) && !/\.(test|d)\.tsx?$/.test(p) ? [p] : [];
const files = targets.flatMap(walk);
const scope = (opt("--scope") ?? "auto") as "auto" | "any" | "scene";
const all: { file: string; findings: Finding[] }[] = files.map((f) => ({ file: relative(process.cwd(), f), findings: lint(readFileSync(f, "utf8"), { scope }) })).filter((r) => r.findings.length);
const errors = all.reduce((n, r) => n + r.findings.filter((f) => f.severity === "error").length, 0);
const warnings = all.reduce((n, r) => n + r.findings.length, 0) - errors;

if (flag("--json")) console.log(JSON.stringify({ files: files.length, errors, warnings, results: all }, null, 1));
else {
  for (const r of all) {
    console.log(c(4, r.file));
    for (const f of r.findings) {
      console.log(`  ${String(f.line).padStart(4)}:${String(f.col).padEnd(3)} ${f.severity === "error" ? c(31, "error  ") : c(33, "warning")} ${f.message}  ${c(2, f.rule)}`);
      console.log(`           ${c(2, f.text)}`);
      console.log(`           ${c(36, "fix:")} ${f.fix}`);
    }
    console.log("");
  }
  console.log(errors + warnings === 0 ? c(32, `No tells in ${files.length} file(s).`) : `${errors} error(s), ${warnings} warning(s) in ${all.length} of ${files.length} file(s).`);
}
process.exit(errors > 0 || warnings > Number(opt("--max-warnings") ?? Infinity) ? 1 : 0);
