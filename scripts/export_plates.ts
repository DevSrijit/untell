// Writes src/system/media-plates.gen.ts: the files that prepare wrote for each prepared photo or clip (plate,
// plate-top, plate-dim, subject, cutout, ink layers, paper). Usage: bun scripts/export_plates.ts
//
// A block is a pure function and cannot read the disk. The photo block reads this table, so a scene that asks for a
// file that prepare did not write (`dim: true` on footage with no plate-dim.mp4) throws when the scene builds, with
// the command that writes the file. Without the table, the renderer waits for a file that is not there.
// Run it after each prepare (bun scripts/media.ts prepare, python3 scripts/media_video.py).
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const MEDIA = join(ROOT, "assets", "media");
// The files a block can ask for. Sources, music and models are not plates.
const PLATE = /^(plate(-top|-dim)?\.(jpg|mp4)|subject\.png|cutout\.png|paper\.png|ink-[a-z0-9]+\.png)$/i;

const rows: string[] = [];
for (const name of readdirSync(MEDIA).sort()) {
  const dir = join(MEDIA, name);
  if (!statSync(dir).isDirectory() || !existsSync(join(dir, "meta.json"))) continue;
  const files = readdirSync(dir).filter((f) => PLATE.test(f)).sort();
  if (!files.some((f) => f.startsWith("plate"))) continue;
  rows.push(`  ${JSON.stringify(name)}: ${JSON.stringify(files)},`);
}
writeFileSync(join(ROOT, "src/system/media-plates.gen.ts"), [
  "// Generated by scripts/export_plates.ts. Do not edit. The files that prepare wrote for each prepared photo or clip,",
  "// so the photo block can refuse, when the scene builds, a file that is not there (a renderer would wait for it).",
  "// A name that is not in the table is not checked.",
  "export const PLATES: Record<string, string[]> = {",
  ...rows,
  "};",
  "",
].join("\n"));
console.log(`wrote src/system/media-plates.gen.ts (${rows.length} prepared pictures)`);
